/** 给面板用的：带上当前值、所属页面和板块 */
export function describeSettings(env = {}) {
  return SETTINGS_META.map((m) => {
    let value = env[m.key] ?? '';
    if (m.type === 'secret' && value) {
      value = `${value.slice(0, 4)}••••${value.slice(-4)}`;
    }
    return {
      ...m,
      value,
      page: PAGE_OF_GROUP[m.group] || 'settings',
      section: SECTION_OF_GROUP[m.group] || '其他',
    };
  });
}